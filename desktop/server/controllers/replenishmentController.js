const crypto = require('crypto');
const db = require('../db');
const { evaluateProduct, RECENT_WINDOW_DAYS } = require('../utils/replenishment');
const { recomputeProductQuantities } = require('../utils/stockMath');
const { findOrCreateSupplier } = require('../utils/supplierLookup');
const { emitToStore } = require('../realtime');

function createStoreNotification({ storeId, type, severity, message }) {
  db.prepare(
    `INSERT INTO store_notifications (id, store_id, type, severity, audience_role, message)
     VALUES (?,?,?,?,'admin',?)`
  ).run(crypto.randomUUID(), storeId, type, severity, message);
}

/** Pulls recent + prior-period sale totals for every product in one pass. */
function fetchSalesWindows(storeId) {
  const rows = db.prepare(
    `SELECT product_id,
        COALESCE(SUM(CASE WHEN created_at >= datetime('now', ?) THEN quantity END), 0) AS recent_sold,
        COALESCE(SUM(CASE WHEN created_at < datetime('now', ?)
                            AND created_at >= datetime('now', ?) THEN quantity END), 0) AS prior_sold
     FROM stock_movements
     WHERE store_id = ? AND type = 'sale' AND created_at >= datetime('now', ?)
     GROUP BY product_id`
  ).all(
    `-${RECENT_WINDOW_DAYS} days`,
    `-${RECENT_WINDOW_DAYS} days`,
    `-${RECENT_WINDOW_DAYS * 2} days`,
    storeId,
    `-${RECENT_WINDOW_DAYS * 2} days`
  );
  const map = new Map();
  for (const r of rows) map.set(r.product_id, { recentSold: Number(r.recent_sold), priorSold: Number(r.prior_sold) });
  return map;
}

// GET /api/stores/:storeId/replenishment/suggestions
function getSuggestions(req, res) {
  const { storeId } = req.params;
  const products = db.prepare(
    `SELECT id, name, sku, supplier, cost_price, lead_time_days, min_order_qty, auto_reorder, reorder_level,
            (backroom_qty + shelf_qty) AS on_hand
     FROM products WHERE store_id = ?`
  ).all(storeId);
  const salesWindows = fetchSalesWindows(storeId);

  const suggestions = products
    .map((p) => {
      const { recentSold, priorSold } = salesWindows.get(p.id) || { recentSold: 0, priorSold: 0 };
      const evalResult = evaluateProduct({
        recentSold,
        priorSold,
        leadTimeDays: p.lead_time_days,
        onHand: Number(p.on_hand),
        minOrderQty: p.min_order_qty,
      });
      return {
        productId: p.id,
        name: p.name,
        sku: p.sku,
        supplier: p.supplier,
        onHand: Number(p.on_hand),
        manualReorderLevel: p.reorder_level,
        leadTimeDays: p.lead_time_days,
        autoReorder: !!p.auto_reorder,
        estimatedCost: Math.round(evalResult.suggestedQty * Number(p.cost_price) * 100) / 100,
        ...evalResult,
      };
    })
    .filter((s) => s.needsReorder)
    .sort((a, b) => (a.onHand / (a.reorderPoint || 1)) - (b.onHand / (b.reorderPoint || 1)));

  res.json(suggestions);
}

// POST /api/stores/:storeId/replenishment/purchase-orders
function createPurchaseOrder(req, res) {
  const { storeId } = req.params;
  const { supplier, items, notes, autoGenerated } = req.body;

  if (!supplier || !Array.isArray(items) || items.length === 0) {
    return res.status(400).json({ error: 'supplier and at least one item are required' });
  }

  try {
    const po = db.transaction(() => {
      const costMap = new Map();
      for (const item of items) {
        const row = db.prepare('SELECT cost_price FROM products WHERE id = ? AND store_id = ?').get(item.productId, storeId);
        costMap.set(item.productId, row ? Number(row.cost_price) : 0);
      }
      const totalCost = items.reduce((sum, i) => sum + (costMap.get(i.productId) || 0) * i.quantity, 0);
      const supplierId = findOrCreateSupplier(db, storeId, supplier);

      const poId = crypto.randomUUID();
      db.prepare(
        `INSERT INTO purchase_orders (id, store_id, supplier, supplier_id, auto_generated, notes, total_cost, created_by)
         VALUES (?,?,?,?,?,?,?,?)`
      ).run(poId, storeId, supplier, supplierId, autoGenerated ? 1 : 0, notes || null, totalCost, req.user.sub);

      for (const item of items) {
        db.prepare(
          `INSERT INTO purchase_order_items (id, purchase_order_id, product_id, quantity, unit_cost)
           VALUES (?,?,?,?,?)`
        ).run(crypto.randomUUID(), poId, item.productId, item.quantity, costMap.get(item.productId) || 0);
      }

      createStoreNotification({
        storeId,
        type: autoGenerated ? 'po_auto_generated' : 'po_created',
        severity: 'amber',
        message: autoGenerated
          ? `A draft purchase order for ${supplier} (${items.length} item${items.length > 1 ? 's' : ''}) was generated automatically — review and send it.`
          : `Purchase order created for ${supplier} (${items.length} item${items.length > 1 ? 's' : ''}).`,
      });

      return db.prepare('SELECT * FROM purchase_orders WHERE id = ?').get(poId);
    })();

    res.status(201).json(po);
    try {
      emitToStore(storeId, 'purchase_order:created', po);
    } catch (sideEffectErr) {
      console.error('createPurchaseOrder: post-response realtime side effect failed:', sideEffectErr);
    }
  } catch (err) {
    console.error(err);
    if (!res.headersSent) res.status(500).json({ error: 'Failed to create purchase order' });
  }
}

// GET /api/stores/:storeId/replenishment/purchase-orders
function listPurchaseOrders(req, res) {
  const { storeId } = req.params;
  const orders = db.prepare(
    `SELECT * FROM purchase_orders WHERE store_id = ? ORDER BY created_at DESC LIMIT 200`
  ).all(storeId);
  const itemsByOrder = new Map();
  for (const order of orders) {
    const items = db.prepare(
      `SELECT poi.*, p.name, p.sku FROM purchase_order_items poi
       JOIN products p ON p.id = poi.product_id
       WHERE poi.purchase_order_id = ?`
    ).all(order.id);
    itemsByOrder.set(order.id, items);
  }
  res.json(orders.map((o) => ({ ...o, items: itemsByOrder.get(o.id) || [] })));
}

// PATCH /api/stores/:storeId/replenishment/purchase-orders/:id/send
// Expected delivery = sent time + this order's average product lead time.
// Computed here (not at creation) since that's the moment a real clock
// actually starts running on the supplier — compared against received_at
// later for Supplier Performance Analytics' on-time-rate.
function sendPurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const existing = db.prepare(`SELECT * FROM purchase_orders WHERE id = ? AND store_id = ? AND status = 'draft'`).get(id, storeId);
  if (!existing) return res.status(404).json({ error: 'Draft purchase order not found' });

  const leadRow = db.prepare(
    `SELECT AVG(p.lead_time_days) AS avg_lead_days FROM purchase_order_items poi
     JOIN products p ON p.id = poi.product_id WHERE poi.purchase_order_id = ?`
  ).get(id);
  const avgLeadDays = Number(leadRow?.avg_lead_days) || 7;
  const expectedAt = new Date(Date.now() + avgLeadDays * 24 * 60 * 60 * 1000).toISOString();

  db.prepare(
    `UPDATE purchase_orders SET status = 'sent', sent_at = strftime('%Y-%m-%dT%H:%M:%fZ','now'), expected_at = ? WHERE id = ?`
  ).run(expectedAt, id);
  res.json(db.prepare('SELECT * FROM purchase_orders WHERE id = ?').get(id));
}

// PATCH /api/stores/:storeId/replenishment/purchase-orders/:id/cancel
function cancelPurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const existing = db.prepare(
    `SELECT * FROM purchase_orders WHERE id = ? AND store_id = ? AND status IN ('draft','sent')`
  ).get(id, storeId);
  if (!existing) return res.status(404).json({ error: 'Purchase order not found or already resolved' });
  db.prepare(`UPDATE purchase_orders SET status = 'cancelled' WHERE id = ?`).run(id);
  res.json(db.prepare('SELECT * FROM purchase_orders WHERE id = ?').get(id));
}

// POST /api/stores/:storeId/replenishment/purchase-orders/:id/receive
function receivePurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const { items: receivedOverrides } = req.body;
  const overrideMap = new Map((receivedOverrides || []).map((o) => [o.itemId, o.receivedQuantity]));

  try {
    const updated = db.transaction(() => {
      const po = db.prepare('SELECT * FROM purchase_orders WHERE id = ? AND store_id = ?').get(id, storeId);
      if (!po) { const e = new Error('Purchase order not found'); e.status = 404; throw e; }
      if (po.status === 'received') { const e = new Error('Already received'); e.status = 409; throw e; }
      if (po.status === 'cancelled') { const e = new Error('Cannot receive a cancelled order'); e.status = 409; throw e; }

      const poItems = db.prepare('SELECT * FROM purchase_order_items WHERE purchase_order_id = ?').all(id);
      for (const item of poItems) {
        const receivedQty = overrideMap.has(item.id) ? Number(overrideMap.get(item.id)) : item.quantity;
        if (receivedQty <= 0) continue;

        db.prepare(
          `INSERT INTO stock_movements (id, store_id, product_id, type, quantity, note, performed_by)
           VALUES (?,?,?,'arrival',?,?,?)`
        ).run(crypto.randomUUID(), storeId, item.product_id, receivedQty, `Received from purchase order ${po.id.slice(0, 8)}`, req.user.sub);
        recomputeProductQuantities(db, item.product_id);
        db.prepare('UPDATE purchase_order_items SET received_quantity = ? WHERE id = ?').run(receivedQty, item.id);
      }

      db.prepare(
        `UPDATE purchase_orders SET status = 'received', received_by = ?, received_at = strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id = ?`
      ).run(req.user.sub, id);

      return db.prepare('SELECT * FROM purchase_orders WHERE id = ?').get(id);
    })();

    res.json(updated);
    try {
      emitToStore(storeId, 'purchase_order:received', updated);
      for (const item of db.prepare('SELECT DISTINCT product_id FROM purchase_order_items WHERE purchase_order_id = ?').all(id)) {
        emitToStore(storeId, 'product:updated', db.prepare('SELECT * FROM products WHERE id = ?').get(item.product_id));
      }
    } catch (sideEffectErr) {
      console.error('receivePurchaseOrder: post-response realtime side effect failed:', sideEffectErr);
    }
  } catch (err) {
    console.error(err);
    if (!res.headersSent) res.status(err.status || 500).json({ error: err.message || 'Failed to receive purchase order' });
  }
}

