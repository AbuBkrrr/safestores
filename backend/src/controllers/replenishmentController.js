const db = require('../config/db');
const { evaluateProduct, RECENT_WINDOW_DAYS } = require('../utils/replenishment');
const { recomputeProductQuantities } = require('../utils/stockMath');
const { findOrCreateSupplier } = require('../utils/supplierLookup');
const { emitToStore } = require('../realtime');

async function createStoreNotification(client, { storeId, type, severity, message }) {
  await client.query(
    `INSERT INTO store_notifications (store_id, type, severity, audience_role, message) VALUES ($1,$2,$3,'admin',$4)`,
    [storeId, type, severity, message]
  );
}

/** Pulls recent + prior-period sale totals for every product in one pass. */
async function fetchSalesWindows(storeId) {
  const { rows } = await db.query(
    `SELECT product_id,
        COALESCE(SUM(CASE WHEN created_at >= now() - interval '${RECENT_WINDOW_DAYS} days' THEN quantity END), 0) AS recent_sold,
        COALESCE(SUM(CASE WHEN created_at < now() - interval '${RECENT_WINDOW_DAYS} days'
                            AND created_at >= now() - interval '${RECENT_WINDOW_DAYS * 2} days' THEN quantity END), 0) AS prior_sold
     FROM stock_movements
     WHERE store_id = $1 AND type = 'sale' AND created_at >= now() - interval '${RECENT_WINDOW_DAYS * 2} days'
     GROUP BY product_id`,
    [storeId]
  );
  const map = new Map();
  for (const r of rows) map.set(r.product_id, { recentSold: Number(r.recent_sold), priorSold: Number(r.prior_sold) });
  return map;
}

// GET /api/stores/:storeId/replenishment/suggestions
async function getSuggestions(req, res) {
  const { storeId } = req.params;
  const { rows: products } = await db.query(
    `SELECT id, name, sku, supplier, cost_price, lead_time_days, min_order_qty, auto_reorder, reorder_level,
            (backroom_qty + shelf_qty) AS on_hand
     FROM products WHERE store_id = $1`,
    [storeId]
  );
  const salesWindows = await fetchSalesWindows(storeId);

  const suggestions = products
    .map((p) => {
      const { recentSold, priorSold } = salesWindows.get(p.id) || { recentSold: 0, priorSold: 0 };
      const evalResult = evaluateProduct({
        recentSold,
        priorSold,
        leadTimeDays: p.lead_time_days,
        onHand: Number(p.on_hand),
        minOrderQty: p.min_order_qty,
      });
      return {
        productId: p.id,
        name: p.name,
        sku: p.sku,
        supplier: p.supplier,
        onHand: Number(p.on_hand),
        manualReorderLevel: p.reorder_level,
        leadTimeDays: p.lead_time_days,
        autoReorder: !!p.auto_reorder,
        estimatedCost: Math.round(evalResult.suggestedQty * Number(p.cost_price) * 100) / 100,
        ...evalResult,
      };
    })
    .filter((s) => s.needsReorder)
    .sort((a, b) => (a.onHand / (a.reorderPoint || 1)) - (b.onHand / (b.reorderPoint || 1)));

  res.json(suggestions);
}

// POST /api/stores/:storeId/replenishment/purchase-orders
async function createPurchaseOrder(req, res) {
  const { storeId } = req.params;
  const { supplier, items, notes, autoGenerated } = req.body;
  if (!supplier || !Array.isArray(items) || items.length === 0) {
    return res.status(400).json({ error: 'supplier and at least one item are required' });
  }

  const client = await db.pool.connect();
  try {
    await client.query('BEGIN');
    const costMap = new Map();
    for (const item of items) {
      const { rows } = await client.query('SELECT cost_price FROM products WHERE id = $1 AND store_id = $2', [item.productId, storeId]);
      costMap.set(item.productId, rows[0] ? Number(rows[0].cost_price) : 0);
    }
    const totalCost = items.reduce((sum, i) => sum + (costMap.get(i.productId) || 0) * i.quantity, 0);
    const supplierId = await findOrCreateSupplier(client, storeId, supplier);

    const { rows: poRows } = await client.query(
      `INSERT INTO purchase_orders (store_id, supplier, supplier_id, auto_generated, notes, total_cost, created_by)
       VALUES ($1,$2,$3,$4,$5,$6,$7) RETURNING *`,
      [storeId, supplier, supplierId, !!autoGenerated, notes || null, totalCost, req.user.sub]
    );
    const po = poRows[0];

    for (const item of items) {
      await client.query(
        `INSERT INTO purchase_order_items (purchase_order_id, product_id, quantity, unit_cost) VALUES ($1,$2,$3,$4)`,
        [po.id, item.productId, item.quantity, costMap.get(item.productId) || 0]
      );
    }

    await createStoreNotification(client, {
      storeId,
      type: autoGenerated ? 'po_auto_generated' : 'po_created',
      severity: 'amber',
      message: autoGenerated
        ? `A draft purchase order for ${supplier} (${items.length} item${items.length > 1 ? 's' : ''}) was generated automatically — review and send it.`
        : `Purchase order created for ${supplier} (${items.length} item${items.length > 1 ? 's' : ''}).`,
    });

    await client.query('COMMIT');
    res.status(201).json(po);
    try {
      emitToStore(storeId, 'purchase_order:created', po);
    } catch (sideEffectErr) {
      console.error('createPurchaseOrder: post-response realtime side effect failed:', sideEffectErr);
    }
  } catch (err) {
    await client.query('ROLLBACK');
    console.error(err);
    if (!res.headersSent) res.status(500).json({ error: 'Failed to create purchase order' });
  } finally {
    client.release();
  }
}

// GET /api/stores/:storeId/replenishment/purchase-orders
async function listPurchaseOrders(req, res) {
  const { storeId } = req.params;
  const { rows: orders } = await db.query(
    `SELECT * FROM purchase_orders WHERE store_id = $1 ORDER BY created_at DESC LIMIT 200`,
    [storeId]
  );
  const result = [];
  for (const order of orders) {
    const { rows: items } = await db.query(
      `SELECT poi.*, p.name, p.sku FROM purchase_order_items poi
       JOIN products p ON p.id = poi.product_id
       WHERE poi.purchase_order_id = $1`,
      [order.id]
    );
    result.push({ ...order, items });
  }
  res.json(result);
}

// PATCH /api/stores/:storeId/replenishment/purchase-orders/:id/send
// Expected delivery = sent time + this order's average product lead time.
// Computed here (not at creation) since that's the moment a real clock
// actually starts running on the supplier — compared against received_at
// later for Supplier Performance Analytics' on-time-rate.
async function sendPurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const { rows: existingRows } = await db.query(
    `SELECT * FROM purchase_orders WHERE id = $1 AND store_id = $2 AND status = 'draft'`,
    [id, storeId]
  );
  if (!existingRows[0]) return res.status(404).json({ error: 'Draft purchase order not found' });

  const { rows: leadRows } = await db.query(
    `SELECT AVG(p.lead_time_days) AS avg_lead_days FROM purchase_order_items poi
     JOIN products p ON p.id = poi.product_id WHERE poi.purchase_order_id = $1`,
    [id]
  );
  const avgLeadDays = Number(leadRows[0]?.avg_lead_days) || 7;

  const { rows } = await db.query(
    `UPDATE purchase_orders SET status = 'sent', sent_at = now(), expected_at = now() + ($1 || ' days')::interval WHERE id = $2 RETURNING *`,
    [avgLeadDays, id]
  );
  res.json(rows[0]);
}

// PATCH /api/stores/:storeId/replenishment/purchase-orders/:id/cancel
async function cancelPurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const { rows } = await db.query(
    `UPDATE purchase_orders SET status = 'cancelled'
     WHERE id = $1 AND store_id = $2 AND status IN ('draft','sent') RETURNING *`,
    [id, storeId]
  );
  if (!rows[0]) return res.status(404).json({ error: 'Purchase order not found or already resolved' });
  res.json(rows[0]);
}

// POST /api/stores/:storeId/replenishment/purchase-orders/:id/receive
async function receivePurchaseOrder(req, res) {
  const { id, storeId } = req.params;
  const { items: receivedOverrides } = req.body;
  const overrideMap = new Map((receivedOverrides || []).map((o) => [o.itemId, o.receivedQuantity]));

  const client = await db.pool.connect();
  try {
    await client.query('BEGIN');
    const { rows: poRows } = await client.query('SELECT * FROM purchase_orders WHERE id = $1 AND store_id = $2', [id, storeId]);
    const po = poRows[0];
    if (!po) { const e = new Error('Purchase order not found'); e.status = 404; throw e; }
    if (po.status === 'received') { const e = new Error('Already received'); e.status = 409; throw e; }
    if (po.status === 'cancelled') { const e = new Error('Cannot receive a cancelled order'); e.status = 409; throw e; }

    const { rows: poItems } = await client.query('SELECT * FROM purchase_order_items WHERE purchase_order_id = $1', [id]);
    for (const item of poItems) {
      const receivedQty = overrideMap.has(item.id) ? Number(overrideMap.get(item.id)) : item.quantity;
      if (receivedQty <= 0) continue;

      await client.query(
        `INSERT INTO stock_movements (store_id, product_id, type, quantity, note, performed_by) VALUES ($1,$2,'arrival',$3,$4,$5)`,
        [storeId, item.product_id, receivedQty, `Received from purchase order ${po.id.slice(0, 8)}`, req.user.sub]
      );
      await recomputeProductQuantities(client, item.product_id);
      await client.query('UPDATE purchase_order_items SET received_quantity = $1 WHERE id = $2', [receivedQty, item.id]);
    }

    const { rows: updatedRows } = await client.query(
      `UPDATE purchase_orders SET status = 'received', received_by = $1, received_at = now() WHERE id = $2 RETURNING *`,
      [req.user.sub, id]
    );
    await client.query('COMMIT');

    res.json(updatedRows[0]);
    try {
      emitToStore(storeId, 'purchase_order:received', updatedRows[0]);
      const { rows: distinctProducts } = await db.query('SELECT DISTINCT product_id FROM purchase_order_items WHERE purchase_order_id = $1', [id]);
      for (const item of distinctProducts) {
        const { rows: productRows } = await db.query('SELECT * FROM products WHERE id = $1', [item.product_id]);
        emitToStore(storeId, 'product:updated', productRows[0]);
      }
    } catch (sideEffectErr) {
      console.error('receivePurchaseOrder: post-response realtime side effect failed:', sideEffectErr);
    }
  } catch (err) {
    await client.query('ROLLBACK');
    console.error(err);
    if (!res.headersSent) res.status(err.status || 500).json({ error: err.message || 'Failed to receive purchase order' });
  } finally {
    client.release();
  }
}

